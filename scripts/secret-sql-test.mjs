// Writes supabase/tests/database/sms_secret.test.sql from the OTP corpus in
// apps/web/src/lib/__fixtures__/secretCorpus.ts, so the database's own check (private.sms_is_secret,
// migration 77) is tested against exactly the texts the TypeScript detector is.
//
//   node --experimental-strip-types scripts/secret-sql-test.mjs
//
// apps/web/src/lib/sms/secret.test.ts fails when the SQL file is out of date.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
/** @type {{ SECRET_CORPUS: string[], REAL_ALERTS: Array<[string, string]> }} */
const { SECRET_CORPUS, REAL_ALERTS } = await import(new URL('../apps/web/src/lib/__fixtures__/secretCorpus.ts', import.meta.url).href);

/**
 * A Postgres E'' literal that survives any text (quotes, backslashes, newlines, invisible characters).
 * @param {string} text
 */
function lit(text) {
  let out = '';
  for (const ch of text) {
    const cp = ch.codePointAt(0) ?? 0;
    if (ch === "'") out += "\\'";
    else if (ch === '\\') out += '\\\\';
    else if (cp < 0x20 || (cp >= 0x200b && cp <= 0x200f) || cp === 0x2060 || cp === 0xfeff || cp === 0xad) {
      out += `\\u${cp.toString(16).padStart(4, '0')}`;
    } else out += ch;
  }
  return `E'${out}'`;
}

// Every corpus text: dropped by the strictest check AND "as if from SAMPATHTXN" (whose own allowance
// must never free a code). Real alerts are checked with their sender, as they are stored.
const secrets = SECRET_CORPUS.flatMap((t, i) => [
  `select ok(private.sms_is_secret(${lit(t)}), 'drops corpus #${i + 1}');`,
  `select ok(private.sms_is_secret_from('SAMPATHTXN', ${lit(t)}), 'drops corpus #${i + 1} from SAMPATHTXN too');`,
]);
const real = REAL_ALERTS.map(([sender, body], i) =>
  `select ok(not private.sms_is_secret_from(${lit(sender)}, ${lit(body)}), 'keeps real ${sender} alert #${i + 1}');`);

// Texts the import checks below send straight to the RPC.
const firstOtp = SECRET_CORPUS[0];
const sinhalaOtp = SECRET_CORPUS.find((t) => /ගෙවීම/.test(t));
const reversal = REAL_ALERTS.find(([, b]) => /Reversal/.test(b))?.[1];
if (!firstOtp || !sinhalaOtp || !reversal) throw new Error('the corpus lost the texts the import checks use');

const sql = `-- GENERATED by scripts/secret-sql-test.mjs from apps/web/src/lib/__fixtures__/secretCorpus.ts — do not edit.
-- Phase 9 · hard rule 1: the database's OTP check (private.sms_is_secret) drops every corpus text
-- (English / Sinhala / Tamil wording, codes in any position, spaced, dashed, other digit scripts) and
-- keeps every real alert format; an OTP sent through the backup import is never stored.
begin;
create extension if not exists pgtap with schema extensions;
set local search_path = public, extensions;

select plan(${secrets.length + real.length + 3});

${secrets.join('\n')}

${real.join('\n')}

insert into auth.users (id, email) values ('00000000-0000-0000-0000-0000000f9a01', 'secret-owner@test.local');
insert into household (id, name) values ('00000000-0000-0000-0000-0000000f9aaa', 'Secret A');
insert into household_member (household_id, user_id, role) values
  ('00000000-0000-0000-0000-0000000f9aaa', '00000000-0000-0000-0000-0000000f9a01', 'owner');

set local role authenticated;
set local request.jwt.claims to '{"sub":"00000000-0000-0000-0000-0000000f9a01","role":"authenticated"}';

select is(
  public.rpc_sms_import('00000000-0000-0000-0000-0000000f9aaa', jsonb_build_array(
    jsonb_build_object('sender', 'BOC', 'body', ${lit(firstOtp)}, 'received_at', '2026-10-01T04:30:00Z',
                       'fingerprint', 'sotp1', 'kind', 'unknown', 'occurred_on', '2026-10-01'),
    jsonb_build_object('sender', 'BOC', 'body', ${lit(sinhalaOtp)}, 'received_at', '2026-10-01T04:31:00Z',
                       'fingerprint', 'sotp2', 'kind', 'unknown', 'occurred_on', '2026-10-01'))) ->> 'dropped',
  '2', 'OTPs sent straight to the import RPC are dropped');
select is((select count(*)::int from sms_message where household_id = '00000000-0000-0000-0000-0000000f9aaa'), 0,
  'nothing was stored');
select is(
  (public.rpc_sms_import('00000000-0000-0000-0000-0000000f9aaa', jsonb_build_array(
    jsonb_build_object('sender', 'Seylan Bank', 'body', ${lit(reversal)},
                       'received_at', '2026-06-09T02:40:00Z', 'fingerprint', 'srev1', 'kind', 'refund',
                       'institution', 'Seylan', 'last_digits', '6029', 'amount', 6.15, 'currency', 'USD',
                       'bank_txn_id', 'R10063001165', 'occurred_on', '2026-06-09'))) ->> 'stored'),
  '1', 'a real reversal (new kind refund) is stored');

select * from finish();
rollback;
`;

writeFileSync(`${root}supabase/tests/database/sms_secret.test.sql`, sql);
console.log(`sms_secret.test.sql: ${secrets.length} corpus + ${real.length} real alerts`);
